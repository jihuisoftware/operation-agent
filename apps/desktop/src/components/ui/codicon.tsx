const fallbackGlyph = CircleIcon

export function Codicon({ className, name, size, spinning, style, ...props }: CodiconProps) {
  const Glyph = glyphs[name] || fallbackGlyph

  return (
    <span
      aria-hidden="true"
      className={cn(
        'codicon codicon-custom inline-flex items-center justify-center align-middle',
        `codicon-${name}`,
        spinning && 'codicon-modifier-spin',
        className
      )}
      style={{ ...(size != null && size !== '' ? { fontSize: size } : {}), ...style }}
      {...props}
    >
      <Glyph aria-hidden className="size-[1em]" stroke="currentColor" strokeWidth={1.9} />
    </span>
  )
}

/** Wrap a themed icon as a Tabler-shaped icon for nav rows that expect `IconComponent`. */
export function codiconIcon(name: string): IconComponent {
  function CodiconIcon({ className }: { className?: string }) {
    return <Codicon aria-hidden className={cn('leading-none', className)} name={name} size="1em" />
  }

  CodiconIcon.displayName = `Codicon(${name})`

  return CodiconIcon as IconComponent
}
